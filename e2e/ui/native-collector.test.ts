import { test, expect } from '@/playwright/suite';
import { api, createProject, projectText } from '@/api';
import { createBrowserFixture } from '@/tools-dev/browser-fixture';
import { expectIndependentWorkspace, screenshot, useChinese } from '@/playwright/workspace';

type NativeView = HTMLElement & { getURL(): string; executeJavaScript<T>(code: string): Promise<T> };

test('[P0] original native Collect tab navigates, captures, retains state and saves to the real library', async ({ nativePage: page, runtime }, testInfo) => {
  const fixture = await createBrowserFixture();
  try {
    const projectId = await createProject(runtime, '原生采集工作区');
    await useChinese(page);
    await page.goto(`${runtime.webUrl}/?projectId=${projectId}`);
    await expectIndependentWorkspace(page);
    await page.locator('.dock-assets-button').click();
    const sidebar = page.getByTestId('canvas-assets-sidebar');
    await sidebar.getByRole('tab', { name: '采集', exact: true }).click();
    const collector = page.getByTestId('browser-collector');
    await expect(collector).toBeVisible();
    await collector.getByRole('textbox', { name: '浏览器地址', exact: true }).fill(fixture.url);
    await collector.getByRole('textbox', { name: '浏览器地址', exact: true }).press('Enter');
    const view = collector.locator('webview');
    await expect.poll(() => view.evaluate(node => (node as NativeView).getURL())).toBe(`${fixture.url}/`);
    await expect.poll(() => view.evaluate(node => (node as NativeView).executeJavaScript<string>('document.querySelector("#headline")?.textContent'))).toBe('将参考资料采集到当前项目。');
    await screenshot(page, testInfo, '27-original-native-collector-sidebar');
    await sidebar.getByRole('tab', { name: '资产', exact: true }).click();
    await expect(collector).not.toBeVisible();
    await sidebar.getByRole('tab', { name: '采集', exact: true }).click();
    await expect.poll(() => view.evaluate(node => (node as NativeView).getURL())).toBe(`${fixture.url}/`);
    await collector.getByRole('button', { name: '浏览器菜单', exact: true }).click();
    const captured = page.waitForResponse(r => new URL(r.url()).pathname === `/api/projects/${projectId}/files` && r.request().method() === 'POST' && String(r.request().postDataJSON()?.name).endsWith('.png'));
    await page.getByRole('menuitem', { name: '保存当前网页截图（备用）', exact: true }).click();
    const response = await captured;
    expect(response.ok()).toBe(true);
    const filename = (await response.json() as { file: { name: string } }).file.name;
    await expect.poll(async () => (await api<{ files: Array<{ name: string }> }>(runtime, `/api/projects/${projectId}/files`)).files.some(file => file.name === `${filename}.source.json`)).toBe(true);
    const source = JSON.parse(await projectText(runtime, projectId, `${filename}.source.json`));
    expect(source.url).toBe(`${fixture.url}/`);
    expect(source.captureMode).toBe('visible-snapshot');
    await collector.getByRole('button', { name: '已采集素材', exact: true }).click();
    await expect(collector.getByRole('button', { name: `添加 ${filename} 到画布`, exact: true })).toBeVisible();
    await screenshot(page, testInfo, '28-collector-project-tray-with-provenance');
    await collector.getByRole('button', { name: `保存 ${filename} 到个人资产`, exact: true }).click();
    const save = page.getByRole('dialog', { name: '保存到资产', exact: true });
    await expect(save).toBeVisible();
    await screenshot(page, testInfo, '29-canonical-original-save-asset-dialog');
    const uploaded = page.waitForResponse(r => new URL(r.url()).pathname === '/api/asset-library/upload' && r.request().method() === 'POST');
    await save.getByRole('button', { name: '保存', exact: true }).click();
    const uploadResponse = await uploaded;
    expect(uploadResponse.ok()).toBe(true);
    const { asset } = await uploadResponse.json() as { asset: { id: string; source: { projectId?: string; filename?: string } } };
    expect(asset.source.projectId).toBe(projectId);
    expect(asset.source.filename).toBe(filename);
    const libraryBytes = Buffer.from(await (await fetch(`${runtime.serverUrl}/api/asset-library/${asset.id}/content`)).arrayBuffer());
    const projectBytes = Buffer.from(await (await fetch(`${runtime.serverUrl}/api/projects/${projectId}/files/${encodeURIComponent(filename)}`)).arrayBuffer());
    expect(libraryBytes.equals(projectBytes)).toBe(true);
    await expect(save).not.toBeVisible();
    await collector.getByRole('button', { name: `添加 ${filename} 到画布`, exact: true }).click();
    await expect.poll(async () => JSON.stringify((await api<{ state: unknown }>(runtime, `/api/projects/${projectId}/canvas/state`)).state).includes(filename)).toBe(true);
    await collector.getByRole('button', { name: '在标签页浏览器中打开', exact: true }).click();
    await expect(page.getByTestId('design-files-tab')).toHaveAttribute('aria-selected', 'false');
    const expandedView = page.locator('.ws-browser-panel.active webview');
    await expect.poll(() => expandedView.evaluate(node => (node as NativeView).getURL())).toBe(`${fixture.url}/`);
    await page.getByRole('button', { name: '浏览器菜单', exact: true }).click();
    await page.getByRole('menuitem', { name: '浏览器插件', exact: true }).click();
    await expect(page.getByTestId('settings-browser-extension')).toBeVisible();
    await screenshot(page, testInfo, '30-native-browser-extension-entry-and-status');
    await testInfo.attach('collector-evidence.json', { body: JSON.stringify({ projectId, capturedFile: filename, assetId: asset.id, exactBytesRetained: true, expandedOriginalBrowser: true }), contentType: 'application/json' });
  } finally { await fixture.dispose(); }
});

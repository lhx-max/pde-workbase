import { test, expect } from '@/playwright/suite';
import { createProject } from '@/api';
import { expectIndependentWorkspace, screenshot, useChinese } from '@/playwright/workspace';

const referenceSvg = '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="400" viewBox="0 0 640 400"><rect width="640" height="400" fill="#e5eee9"/><circle cx="490" cy="105" r="52" fill="#e3af63"/><path d="M0 350L210 100L380 300L495 185L640 350V400H0Z" fill="#426b62"/></svg>';

test('[P0] original unified image picker exposes all sources and applies a real local asset', async ({ page, runtime }, testInfo) => {
  const id = await createProject(runtime, '统一素材选择器复验');
  const data = new FormData();
  data.set('file', new File([referenceSvg], '参考山景.svg', { type: 'image/svg+xml' }));
  data.set('name', '参考山景');
  data.set('kind', 'image');
  const uploaded = await fetch(`${runtime.serverUrl}/api/asset-library/upload`, { method: 'POST', body: data });
  expect(uploaded.ok, await uploaded.clone().text()).toBe(true);
  await useChinese(page);
  await page.goto(`/?projectId=${id}`);
  await expectIndependentWorkspace(page);
  await page.locator('.dock-primary').click();
  await page.getByRole('menuitem', { name: '图片', exact: true }).click();
  await page.getByRole('button', { name: '添加参考图', exact: true }).click();
  const popup = page.getByRole('dialog').filter({ has: page.locator('.workspace-asset-picker') });
  await expect(popup).toBeVisible();
  for (const name of ['当前画布', '空间资产', '本地上传']) await expect(popup.getByRole('tab', { name, exact: true })).toBeVisible();
  await expect(popup.locator('.wap-header')).toHaveCSS('display', 'flex');
  await expect(popup.locator('.wap-results')).toHaveCSS('overflow-y', 'hidden');
  await screenshot(page, testInfo, 'picker-canvas-source');
  await popup.getByRole('tab', { name: '本地上传', exact: true }).click();
  await expect(popup.locator('input[type="file"]')).toHaveAttribute('accept', 'image/*');
  await screenshot(page, testInfo, 'picker-upload-source');
  await popup.getByRole('tab', { name: '空间资产', exact: true }).click();
  const choice = popup.getByRole('button', { name: /^参考山景/ });
  await expect(choice).toBeVisible();
  await choice.click();
  await expect(choice).toHaveAttribute('aria-pressed', 'true');
  await screenshot(page, testInfo, 'picker-local-asset-selection');
  await popup.getByRole('button', { name: '预览 参考山景', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '参考山景', exact: true });
  await expect(detail).toBeVisible();
  const image = detail.getByRole('img', { name: '参考山景', exact: true });
  await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(640);
  await screenshot(page, testInfo, 'picker-real-asset-preview');
  await detail.getByRole('button', { name: '关闭资产详情', exact: true }).click();
  await expect(detail).toHaveCount(0);
  await expect(choice).toHaveAttribute('aria-pressed', 'true');
  await popup.locator('.wap-footer').getByRole('button', { name: '使用', exact: true }).click();
  await expect(popup).toHaveCount(0);
  await expect(page.getByRole('button', { name: /移除.*参考山景/ })).toBeVisible();
  await screenshot(page, testInfo, 'picker-applied-reference');
});

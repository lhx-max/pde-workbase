import { test, expect } from '@/playwright/suite';
import { api, createProject, writeText } from '@/api';
import { expectIndependentWorkspace, openLauncher, screenshot, useEnglish } from '@/playwright/workspace';

test('[P0] original three tabs, local space CRUD, asset creation, favorite and canvas import', async ({ page, runtime }, testInfo) => {
  const projectId = await createProject(runtime, 'Library and collection workspace');
  await writeText(runtime, projectId, 'canvas-note.md', '# Project-local note');
  await useEnglish(page);
  await page.goto(`${runtime.webUrl}/?projectId=${projectId}`);
  await expectIndependentWorkspace(page);
  await page.locator('.dock-assets-button').click();
  const sidebar = page.getByTestId('canvas-assets-sidebar');
  await expect(sidebar).toBeVisible();
  for (const name of ['Canvas', 'Assets', 'Collect']) await expect(sidebar.getByRole('tab', { name, exact: true })).toBeVisible();
  await expect(page.getByTestId('canvas-sidebar-file-canvas-note.md')).toBeVisible();
  await screenshot(page, testInfo, '20-three-original-sidebar-tabs');
  await sidebar.getByRole('tab', { name: 'Collect', exact: true }).click();
  await expect(sidebar.getByText('Collect while browsing on desktop', { exact: true })).toBeVisible();
  await screenshot(page, testInfo, '21-web-collector-native-capability-boundary');
  await sidebar.getByRole('tab', { name: 'Assets', exact: true }).click();
  await sidebar.getByRole('button', { name: 'Choose asset space' }).click();
  await page.getByRole('menuitem', { name: '＋ New space', exact: true }).click();
  const createSpace = page.getByRole('dialog', { name: 'New space', exact: true });
  await createSpace.getByRole('textbox', { name: 'space name' }).fill('Campaign references');
  const spaceSaved = page.waitForResponse(r => new URL(r.url()).pathname === '/api/asset-library/spaces' && r.request().method() === 'POST');
  await createSpace.getByRole('button', { name: 'Create space', exact: true }).click();
  expect((await spaceSaved).ok()).toBe(true);
  await expect(createSpace).not.toBeVisible();
  await expect(sidebar.getByRole('button', { name: 'Choose asset space' })).toHaveText('Campaign references');
  const spaces = await api<{ folders: Array<{ id: string; name: string }> }>(runtime, '/api/asset-library/spaces');
  const spaceId = spaces.folders.find(space => space.name === 'Campaign references')!.id;
  await sidebar.getByRole('button', { name: 'Text', exact: true }).click();
  await sidebar.getByRole('button', { name: 'New', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'New personal asset', exact: true });
  await create.getByRole('textbox', { name: 'Name', exact: true }).fill('Reusable research note');
  await create.getByRole('textbox', { name: 'Content', exact: true }).fill('# Browser research\n\nA reusable reference with real local storage.');
  const assetSaved = page.waitForResponse(r => new URL(r.url()).pathname === '/api/asset-library' && r.request().method() === 'POST');
  await create.getByRole('button', { name: 'Save', exact: true }).click();
  const saved = await assetSaved;
  expect(saved.ok()).toBe(true);
  const { asset } = await saved.json() as { asset: { id: string; name: string; spaceId: string } };
  expect(asset.spaceId).toBe(spaceId);
  await expect(create).not.toBeVisible();
  const card = sidebar.locator('.community-template-card').filter({ has: page.getByRole('button', { name: 'Open Reusable research note', exact: true }) });
  await expect(card).toBeVisible();
  await card.hover();
  await card.getByRole('button', { name: 'More actions for Reusable research note' }).click();
  const favoriteSaved = page.waitForResponse(r => new URL(r.url()).pathname === `/api/asset-library/${asset.id}` && r.request().method() === 'PATCH');
  await page.getByRole('menuitem', { name: 'Favorite', exact: true }).click();
  expect((await favoriteSaved).ok()).toBe(true);
  await expect.poll(async () => (await api<{ asset: { favorite: boolean } }>(runtime, `/api/asset-library/${asset.id}`)).asset.favorite).toBe(true);
  await screenshot(page, testInfo, '22-original-local-asset-cards-and-space');
  await card.hover();
  const imported = page.waitForResponse(r => new URL(r.url()).pathname === `/api/projects/${projectId}/asset-library/import` && r.request().method() === 'POST');
  await card.getByRole('button', { name: 'Add to board', exact: true }).click();
  const importResponse = await imported;
  expect(importResponse.ok()).toBe(true);
  const { files } = await importResponse.json() as { files: Array<{ name: string }> };
  const filename = files[0]!.name;
  await expect.poll(async () => JSON.stringify((await api<{ state: unknown }>(runtime, `/api/projects/${projectId}/canvas/state`)).state).includes(filename)).toBe(true);
  const used = await api<{ uses: Array<{ projectId: string }> }>(runtime, `/api/asset-library/${asset.id}/uses`);
  expect(used.uses.some(use => use.projectId === projectId)).toBe(true);
  await sidebar.getByRole('button', { name: 'Open full asset library', exact: true }).click();
  const library = page.getByRole('dialog', { name: 'Asset library', exact: true });
  await expect(library.getByRole('button', { name: 'Open Reusable research note', exact: true })).toBeVisible();
  await screenshot(page, testInfo, '23-original-expanded-asset-library');
  await library.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(library).not.toBeVisible();
  await page.locator('.dock-assets-button').click();
  await expect(sidebar).toBeVisible();
  // Removing a space through the real original confirmation moves, never orphans, its assets.
  await sidebar.getByRole('button', { name: 'Choose asset space' }).click();
  await page.getByRole('menuitem', { name: 'Delete space Campaign references', exact: true }).click();
  const deletion = page.getByRole('dialog');
  await expect(deletion.getByRole('checkbox', { name: 'Move', exact: true })).toBeChecked();
  await screenshot(page, testInfo, '24-space-removal-preserves-assets-by-default');
  const removed = page.waitForResponse(r => new URL(r.url()).pathname === '/api/asset-library/spaces' && r.request().method() === 'POST');
  await deletion.getByRole('button', { name: 'Delete', exact: true }).click();
  expect((await removed).ok()).toBe(true);
  await expect(deletion).not.toBeVisible();
  expect((await api<{ asset: { spaceId: string } }>(runtime, `/api/asset-library/${asset.id}`)).asset.spaceId).toBe('default-project');
  await sidebar.getByRole('tab', { name: 'Canvas', exact: true }).click();
  await expect(page.getByTestId(`canvas-sidebar-file-${filename}`)).toBeVisible();
  await page.reload();
  await expectIndependentWorkspace(page);
  expect(JSON.stringify((await api<{ state: unknown }>(runtime, `/api/projects/${projectId}/canvas/state`)).state)).toContain(filename);
  await testInfo.attach('local-library-evidence.json', { body: JSON.stringify({ projectId, assetId: asset.id, importedFile: filename, removedSpaceId: spaceId, retainedInDefaultSpace: true }), contentType: 'application/json' });
});

test('[P0] browser preferences persist through HTTP and extension settings remain reachable on Web', async ({ page, runtime }, testInfo) => {
  const projectId = await createProject(runtime, 'Browser preferences verification');
  await useEnglish(page);
  await page.goto(`${runtime.webUrl}/?projectId=${projectId}`);
  await expectIndependentWorkspace(page);
  await openLauncher(page);
  await page.getByRole('menuitem', { name: 'New Browser', exact: true }).click();
  await expect(page.getByTestId('design-browser-home')).toBeVisible();
  await page.getByRole('button', { name: 'Capture overlays', exact: true }).click();
  const enabled = page.getByRole('switch', { name: 'Show capture overlays', exact: true });
  await expect(enabled).toBeEnabled();
  const before = await api<{ revision: number; preferences: { browserCapture?: { enabled: boolean } } }>(runtime, '/api/browser-preferences');
  const persisted = page.waitForResponse(r => new URL(r.url()).pathname === '/api/browser-preferences' && r.request().method() === 'PUT');
  await enabled.click();
  expect((await persisted).ok()).toBe(true);
  const after = await api<typeof before>(runtime, '/api/browser-preferences');
  expect(after.revision).toBeGreaterThan(before.revision);
  expect(after.preferences.browserCapture!.enabled).toBe(!(before.preferences.browserCapture?.enabled ?? true));
  await screenshot(page, testInfo, '25-browser-capture-preferences');
  await page.reload();
  await expect(page.getByTestId('design-browser-home')).toBeVisible();
  await page.getByRole('button', { name: 'Capture overlays', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Show capture overlays', exact: true })).toHaveAttribute('aria-checked', String(after.preferences.browserCapture!.enabled));
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Browser menu', exact: true }).click();
  await page.getByRole('menuitem', { name: /extension/i }).click();
  await expect(page.getByTestId('settings-browser-extension')).toBeVisible();
  await screenshot(page, testInfo, '26-browser-extension-settings-web-boundary');
});
